"""
agriculture_agent.py
====================
AI Agriculture Assistant and Advisory Engine.

Provides an offline, rule-based agronomic expert agent that:
  - Explains crop recommendation decisions in clear, beginner-friendly language
  - Synthesizes soil nutrient inputs (N, P, K, pH) and weather factors into actionable advice
  - Explains disease diagnoses, pathogen biology, organic controls, and chemical treatments
  - Generates holistic Seasonal Farm Action Plans integrating recommendation & disease data
  - Includes transparent reasoning and safety guardrails (KVK consultation & PPE warnings)
  - Operates 100% locally with zero paid API keys required
"""

import re
from typing import Dict, Any, Optional, List

AGENT_DISCLAIMER = (
    "\n\n*Note: This advice is generated by the AI Agriculture Assistant for educational "
    "and decision-support guidance. Verify chemical dosages with your local Krishi Vigyan Kendra (KVK) "
    "or Agricultural Extension Officer before field application.*"
)


class AgricultureAgent:
    """
    Expert Agricultural Advisory Agent.
    Operates rule-based intent parsing, contextual session synthesis, and agronomic reasoning.
    """

    def __init__(self):
        self.name = "Kisan Mitra AI (Smart Agriculture Agent)"

    def answer_query(
        self,
        query: str,
        session_context: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """
        Process user query and return structured response dictionary:
          - response_text: formatted Markdown string
          - intent: identified query intent
          - suggested_next_steps: list of quick actionable next queries
        """
        if not query or not query.strip():
            return {
                "response_text": "Please ask a question regarding crop selection, soil health, fertilizers, or plant diseases.",
                "intent": "EMPTY_QUERY",
                "suggested_next_steps": [
                    "Why was this crop recommended?",
                    "How to manage soil pH?",
                    "What does high nitrogen do?",
                    "Treatment for leaf spots"
                ]
            }

        q = query.lower().strip()
        context = session_context or {}

        # 1. Check for Contextual Crop Recommendation Questions
        if self._is_crop_explanation_query(q):
            return self._handle_crop_explanation(q, context)

        # 2. Check for Contextual Disease Questions
        if self._is_disease_query(q):
            return self._handle_disease_explanation(q, context)

        # 3. Check for Integrated Farm Action Plan
        if any(w in q for w in ["action plan", "farm plan", "combine results", "next steps", "summary"]):
            return self._handle_integrated_action_plan(context)

        # 4. Soil pH Management
        if "ph" in q:
            return self._handle_soil_ph_query(q)

        # 5. Nitrogen, Phosphorus, Potassium (N-P-K) Nutrients
        if any(w in q for w in ["nitrogen", "phosphorus", "potassium", "npk", "urea", "dap", "potash"]):
            return self._handle_nutrient_query(q)

        # 6. Irrigation and Water Management
        if any(w in q for w in ["irrigation", "water", "watering", "rainfall", "drip", "sprinkler"]):
            return self._handle_irrigation_query(q)

        # 7. Cropping Seasons (Kharif, Rabi, Zaid)
        if any(w in q for w in ["kharif", "rabi", "zaid", "season", "monsoon", "winter crop"]):
            return self._handle_season_query(q)

        # 8. Greetings and Help
        if any(w in q for w in ["hello", "hi", "hey", "who are you", "help", "guide"]):
            return self._handle_greeting()

        # 9. Fallback Agronomic Response
        return self._handle_general_agronomy(q, context)

    # ---------------- INTENT MATCHERS ----------------

    def _is_crop_explanation_query(self, q: str) -> bool:
        triggers = [
            "why this crop", "why was", "why rice", "why maize", "why cotton",
            "explain recommendation", "explain crop", "how was it chosen",
            "why recommended", "soil suitability", "reason for"
        ]
        return any(t in q for t in triggers)

    def _is_disease_query(self, q: str) -> bool:
        triggers = [
            "disease", "blight", "rust", "scab", "rot", "mold", "spot", "virus",
            "symptom", "cure", "treatment", "fungicide", "spray", "pesticide",
            "mancozeb", "leaf infection", "yellow leaf"
        ]
        return any(t in q for t in triggers)

    # ---------------- HANDLERS ----------------

    def _handle_crop_explanation(self, q: str, context: Dict[str, Any]) -> Dict[str, Any]:
        crop_data = context.get("last_crop_recommendation")

        if not crop_data:
            return {
                "response_text": (
                    "### Crop Recommendation Context Missing\n\n"
                    "I don't have a recent crop recommendation saved in your current session.\n\n"
                    "**Next Step**: Go to the **Crop Recommendation** tab, enter your soil (N, P, K, pH) "
                    "and climate (temperature, humidity, rainfall) parameters, and click **Recommend Best Crop**. "
                    "Once calculated, I will explain exactly why that crop matches your field conditions!"
                    + AGENT_DISCLAIMER
                ),
                "intent": "CROP_EXPLANATION_NO_CONTEXT",
                "suggested_next_steps": [
                    "Go to Crop Recommendation tab",
                    "What are ideal soil conditions for Rice?",
                    "How to interpret N-P-K values?"
                ]
            }

        rec_crop = crop_data.get("recommended_crop", "Recommended Crop")
        conf = crop_data.get("confidence", 0.0)
        inputs = crop_data.get("inputs", {})
        profile = crop_data.get("profile", {})
        gaps = crop_data.get("soil_gap_analysis", [])

        # Formulate explanation
        lines = [
            f"### Scientific Reasoning: Why **{rec_crop}** Was Recommended\n",
            f"Our Random Forest Classification model identified **{rec_crop}** with **{conf}% confidence** "
            f"based on your field parameters:\n",
            f"- **Soil Nutrients**: Nitrogen: `{inputs.get('N', 'N/A')} mg/kg`, Phosphorus: `{inputs.get('P', 'N/A')} mg/kg`, Potassium: `{inputs.get('K', 'N/A')} mg/kg`",
            f"- **Soil Acidity**: pH `{inputs.get('ph', 'N/A')}`",
            f"- **Climatic Factors**: Temperature: `{inputs.get('temperature', 'N/A')} °C`, Humidity: `{inputs.get('humidity', 'N/A')} %`, Rainfall: `{inputs.get('rainfall', 'N/A')} mm`\n",
            "#### Agronomic Compatibility Highlights:",
            f"1. **Crop Category & Season**: {rec_crop} is a {profile.get('category', 'crop')} primarily grown during the **{profile.get('season', 'growing season')}** with a duration of {profile.get('duration', 'a standard cycle')}.",
            f"2. **Water & Soil Needs**: It thrives best in {profile.get('soil_type', 'well-drained soil')} with {profile.get('water_need', 'moderate water')}."
        ]

        # Highlight gaps if any
        deficient = [g for g in gaps if g.get("status") == "Below Optimal"]
        excess = [g for g in gaps if g.get("status") == "Above Optimal"]

        if deficient or excess:
            lines.append("\n#### Recommended Soil Adjustments:")
            for d in deficient[:2]:
                lines.append(f"- ⚠️ **{d['name']}**: {d['recommendation']}")
            for e in excess[:1]:
                lines.append(f"- ℹ️ **{e['name']}**: {e['recommendation']}")
        else:
            lines.append("\n#### Soil Balance:\n- Your soil and climate parameters fall right in the optimal sweet spot for this crop!")

        lines.append(f"\n**Agronomic Tip**: {profile.get('tips', 'Follow local extension advisory.')}")
        lines.append(AGENT_DISCLAIMER)

        return {
            "response_text": "\n".join(lines),
            "intent": "CROP_EXPLANATION_SUCCESS",
            "suggested_next_steps": [
                f"What fertilizer schedule should I follow for {rec_crop}?",
                f"What irrigation method suits {rec_crop} best?",
                "Give me a seasonal farm action plan"
            ]
        }

    def _handle_disease_explanation(self, q: str, context: Dict[str, Any]) -> Dict[str, Any]:
        disease_data = context.get("last_disease_detection")

        if disease_data and disease_data.get("success"):
            pred_class = disease_data.get("predicted_class", "")
            disp = disease_data.get("display_name", pred_class)
            conf = disease_data.get("confidence", 0.0)
            is_healthy = disease_data.get("is_healthy", False)
            advisory = disease_data.get("advisory", {})

            if is_healthy:
                resp = (
                    f"### Diagnosis Review: **{disp}**\n\n"
                    f"Your plant leaf was diagnosed as **Healthy** with **{conf}% confidence**.\n\n"
                    f"**Symptoms**: {advisory.get('symptoms', 'Normal foliage without lesions.')}\n\n"
                    f"**Maintenance Recommendations**:\n"
                    f"1. {advisory.get('organic_remedy', 'Maintain balanced NPK fertilization.')}\n"
                    f"2. {advisory.get('prevention', 'Scout field weekly for early pest vectors.')}\n"
                    f"{AGENT_DISCLAIMER}"
                )
            else:
                resp = (
                    f"### Disease Advisory: **{disp}**\n\n"
                    f"- **Identified Pathogen**: `{advisory.get('pathogen', 'Pathogen')}`\n"
                    f"- **Model Confidence**: `{conf}%`\n\n"
                    f"#### 1. Visual Symptoms Identification\n"
                    f"{advisory.get('symptoms', 'Leaf spotting and chlorosis.')}\n\n"
                    f"#### 2. Immediate Eco-Friendly & Organic Controls\n"
                    f"{advisory.get('organic_remedy', 'Apply neem oil and prune diseased foliage.')}\n\n"
                    f"#### 3. Targeted Chemical Treatment\n"
                    f"{advisory.get('chemical_treatment', 'Consult local extension officer for certified fungicide.')}\n\n"
                    f"#### 4. Preventive Farm Sanitation & Soil Care\n"
                    f"{advisory.get('prevention', 'Rotate crops and avoid overhead watering.')}\n"
                    f"{AGENT_DISCLAIMER}"
                )

            return {
                "response_text": resp,
                "intent": "DISEASE_EXPLANATION_SUCCESS",
                "suggested_next_steps": [
                    "How to prepare Neem oil spray?",
                    "What fungicide should I use?",
                    "Give me a seasonal farm action plan"
                ]
            }

        # Fallback if no image uploaded yet: check if query specifies a disease name
        return {
            "response_text": (
                "### Crop Disease Advisory Engine\n\n"
                "I can analyze leaf diseases, identify fungal/bacterial pathogens, and provide organic and chemical treatments.\n\n"
                "**How to use**:\n"
                "1. Go to the **Crop Disease Advisory** tab and upload a plant leaf image, or\n"
                "2. Browse the built-in **Plant Disease Catalog** on that tab, or\n"
                "3. Ask me about a specific crop disease right here (e.g., *'How to cure Potato Early Blight?'*, *'Tomato Late Blight remedy'*)."
                + AGENT_DISCLAIMER
            ),
            "intent": "DISEASE_GENERAL_GUIDE",
            "suggested_next_steps": [
                "How to manage Potato Early Blight?",
                "Remedy for Tomato Late Blight?",
                "How to control Powdery Mildew in Cucurbits?"
            ]
        }

    def _handle_integrated_action_plan(self, context: Dict[str, Any]) -> Dict[str, Any]:
        crop_data = context.get("last_crop_recommendation")
        disease_data = context.get("last_disease_detection")

        crop_name = crop_data.get("recommended_crop") if crop_data else "Recommended Crop"
        has_crop = crop_data is not None
        has_disease = disease_data is not None and disease_data.get("success")

        lines = [
            "### Integrated Seasonal Farm Action Plan\n",
            "This synthesized plan coordinates your soil profile, crop choice, and plant health management into an actionable 4-phase schedule:\n"
        ]

        # Phase 1: Pre-sowing & Soil Preparation
        lines.append("#### Phase 1: Land Preparation & Basal Nutrition (Day -15 to Day 0)")
        if has_crop:
            gaps = crop_data.get("soil_gap_analysis", [])
            lines.append(f"- **Target Crop**: Plan field layout for **{crop_name}**.")
            for g in gaps:
                if g.get("status") != "Optimal":
                    lines.append(f"  - *{g['name']} correction*: {g['recommendation']}")
        else:
            lines.append("- Perform comprehensive soil testing for Nitrogen, Phosphorus, Potassium, and pH.")
            lines.append("- Incorporate 5 to 10 tons/hectare of well-decomposed Farmyard Manure (FYM) or Vermicompost.")

        # Phase 2: Sowing & Early Establishment
        lines.append("\n#### Phase 2: Sowing & Seed Treatment (Day 1 to Day 30)")
        lines.append("- **Seed Treatment**: Treat seeds with *Trichoderma viride* (4 g/kg seed) or *Rhizobium* to prevent damping-off and promote early nodulation.")
        lines.append("- **Sowing Depth**: Sow at optimal depth to ensure rapid uniform emergence.")
        lines.append("- **Watering**: Ensure moist seedbed without water stagnation.")

        # Phase 3: Vegetative Growth & Pest/Disease Monitoring
        lines.append("\n#### Phase 3: Crop Protection & Nutrient Management (Day 30 to Day 70)")
        if has_disease and not disease_data.get("is_healthy"):
            d_name = disease_data.get("display_name", "Identified Disease")
            advisory = disease_data.get("advisory", {})
            lines.append(f"- 🚨 **Active Disease Advisory Alert ({d_name})**:")
            lines.append(f"  - *Organic action*: {advisory.get('organic_remedy', 'Neem oil spray.')}")
            lines.append(f"  - *Chemical spray*: {advisory.get('chemical_treatment', 'Consult extension officer.')}")
        else:
            lines.append("- Install yellow and blue sticky traps (10-15/acre) to scout for sucking pests.")
            lines.append("- Practice preventative foliar spray of 0.5% cold-pressed neem oil.")

        # Phase 4: Maturity & Harvest
        lines.append("\n#### Phase 4: Maturity & Post-Harvest Care")
        lines.append("- Withhold irrigation 7 to 10 days prior to harvest to prevent post-harvest rot.")
        lines.append("- Destroy crop residue or compost thoroughly to disrupt pest life cycles for the next season.")
        lines.append(AGENT_DISCLAIMER)

        return {
            "response_text": "\n".join(lines),
            "intent": "INTEGRATED_ACTION_PLAN",
            "suggested_next_steps": [
                "How to prepare Trichoderma seed treatment?",
                "What is the best irrigation schedule?",
                "Explain my crop recommendation"
            ]
        }

    def _handle_soil_ph_query(self, q: str) -> Dict[str, Any]:
        resp = (
            "### Comprehensive Soil pH Management Guide\n\n"
            "Soil pH measures soil acidity or alkalinity on a scale of 0 to 14, where **6.0 to 7.2** is optimal for most agricultural crops.\n\n"
            "| pH Range | Classification | Nutrient Availability Impact |\n"
            "| :--- | :--- | :--- |\n"
            "| **< 5.5** | Strongly Acidic | Phosphorus gets locked by Aluminum & Iron; Calcium/Magnesium deficient |\n"
            "| **6.0 - 7.0** | Slightly Acidic to Neutral | **Optimal**: Maximum availability of all macro and micro-nutrients |\n"
            "| **> 7.8** | Alkaline / Saline | Iron, Zinc, Manganese, and Copper deficiencies common |\n\n"
            "#### How to Correct Acidic Soil (pH < 6.0):\n"
            "- **Agricultural Lime (Calcium Carbonate, CaCO3)** or **Dolomitic Limestone**: Apply 1-2 tons/ha 3 to 4 weeks before sowing.\n"
            "- Incorporate wood ash in moderate quantities to buffer soil acidity.\n\n"
            "#### How to Correct Alkaline Soil (pH > 7.5):\n"
            "- **Agricultural Gypsum (Calcium Sulfate, CaSO4·2H2O)**: Replaces exchangeable sodium with calcium.\n"
            "- **Elemental Sulfur**: Soil bacteria convert sulfur into sulfuric acid, gradually lowering pH.\n"
            "- Apply well-rotted farmyard manure and green manure (e.g. *Sesbania / Dhaincha*) to produce carbonic acid buffers."
            + AGENT_DISCLAIMER
        )
        return {
            "response_text": resp,
            "intent": "SOIL_PH_MANAGEMENT",
            "suggested_next_steps": [
                "How much gypsum per acre for alkaline soil?",
                "What crops tolerate acidic soil?",
                "How to interpret N-P-K values?"
            ]
        }

    def _handle_nutrient_query(self, q: str) -> Dict[str, Any]:
        resp = (
            "### Essential Primary Soil Nutrients (N - P - K) Guide\n\n"
            "Agricultural crops require the three primary macronutrients in balanced proportions:\n\n"
            "#### 1. Nitrogen (N) — The Growth Driver\n"
            "- **Role**: Builds chlorophyll, proteins, and amino acids; drives vegetative shoot and leaf growth.\n"
            "- **Deficiency Signs**: General yellowing (chlorosis) of older lower leaves, stunted plant height.\n"
            "- **Remedy**: Apply **Urea (46% N)**, Ammonium Sulfate, or organic vermicompost / mustard cake.\n"
            "- **Caution**: Excess Nitrogen causes weak succulent stems prone to lodging and pest attacks.\n\n"
            "#### 2. Phosphorus (P) — The Energy & Root Builder\n"
            "- **Role**: Essential for ATP energy transfer, vigorous root elongation, early flowering, and seed formation.\n"
            "- **Deficiency Signs**: Dark green leaves turning purplish or bronze along margins; delayed maturity.\n"
            "- **Remedy**: Apply **Single Super Phosphate (SSP - 16% P2O5)** or **Di-Ammonium Phosphate (DAP - 18:46:0)** as basal dose.\n\n"
            "#### 3. Potassium (K) — The Quality & Resistance Shield\n"
            "- **Role**: Regulates stomatal opening and transpiration, strengthens cell walls, improves disease resistance, and enhances fruit weight and flavor.\n"
            "- **Deficiency Signs**: Marginal leaf scorch (burnt look on leaf edges and tips).\n"
            "- **Remedy**: Apply **Muriate of Potash (MOP - 60% K2O)** or Potassium Sulfate (SOP)."
            + AGENT_DISCLAIMER
        )
        return {
            "response_text": resp,
            "intent": "SOIL_NUTRIENTS_NPK",
            "suggested_next_steps": [
                "When should DAP be applied vs Urea?",
                "How to correct potassium deficiency?",
                "Explain my crop recommendation"
            ]
        }

    def _handle_irrigation_query(self, q: str) -> Dict[str, Any]:
        resp = (
            "### Modern Water & Irrigation Management Guide\n\n"
            "Water management must balance soil aeration with plant transpiration demands:\n\n"
            "#### 1. Drip Irrigation (Micro-irrigation)\n"
            "- **Water Savings**: 40% - 60% compared to surface flooding.\n"
            "- **Ideal For**: Row crops, vegetables (Tomato, Pepper, Potato), orchards (Banana, Grapes, Pomegranate).\n"
            "- **Advantage**: Delivers water and water-soluble fertilizers (fertigation) directly to the root zone; keeps leaves dry to inhibit fungal foliar diseases.\n\n"
            "#### 2. Sprinkler Irrigation\n"
            "- **Ideal For**: Undulating terrains, pulses, oilseeds, wheat, and leafy vegetables.\n"
            "- **Caution**: Avoid running overhead sprinklers in late evening to prevent long leaf wetness duration, which favors Late Blight and Anthracnose.\n\n"
            "#### 3. Waterlogging & Root Aeration\n"
            "- Roots require oxygen for nutrient uptake. Waterlogging for >48 hours leads to root death and collar rot.\n"
            "- Install drainage trenches along field boundaries in heavy clay soils."
            + AGENT_DISCLAIMER
        )
        return {
            "response_text": resp,
            "intent": "IRRIGATION_WATER",
            "suggested_next_steps": [
                "What crops need low water?",
                "How does drip irrigation prevent disease?",
                "Give me a seasonal farm action plan"
            ]
        }

